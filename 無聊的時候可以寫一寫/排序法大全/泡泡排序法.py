def bubble_sort(arr):
    # 取得陣列的長度 n
    # n 代表目前要排序的資料筆數
    n = len(arr)

    # 若陣列長度小於 2（0 或 1 個元素）
    # 則不需要排序，因為：
    # - 空陣列本來就是排序好的
    # - 只有一個元素也不可能有順序問題
    if n < 2:
        return arr

    # 外層迴圈：控制「排序的回合數」
    # i 代表目前是第幾輪冒泡（第 i 輪）
    # 每一輪結束後，會有「一個最大值」
    # 被推到陣列的最右邊（正確位置）
    for i in range(n):

        # 內層迴圈：負責「相鄰元素比較與交換」
        # 為什麼是 n - i - 1？
        # - 最後 i 個元素在前幾輪已經排好
        # - 不需要再比較
        # - -1 是因為 j 會和 j+1 比較，避免索引超界
        for j in range(n - i - 1):

            # 比較目前元素 arr[j] 與右邊相鄰元素 arr[j+1]
            # 若左邊比右邊大，表示順序錯誤
            if arr[j] > arr[j + 1]:

                # 以下三行為「交換（swap）」操作
                # 將較大的值往右移
                temp = arr[j]          # 暫存左邊元素
                arr[j] = arr[j + 1]    # 將右邊較小值放到左邊
                arr[j + 1] = temp      # 將原本左邊較大值放到右邊

        # 印出每一輪排序結束後的陣列狀態
        # 這一行不是排序必要邏輯
        # 但非常適合用來「觀察 Bubble Sort 的冒泡過程」
        print(arr)

    # 排序完成後，回傳排序好的陣列
    # 此排序為 in-place（直接修改原陣列）
    return arr


# ------------------ 主程式區 ------------------

# 建立一個尚未排序的整數陣列
arr = [8, 42, 15, 77, 3, 91, 56, 24, 68, 30]

# 印出排序前的原始陣列
print(arr)

# 呼叫 bubble_sort 函式進行排序
# 並印出排序後的結果
print(bubble_sort(arr))


