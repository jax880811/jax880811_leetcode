class Solution:
    def addBinary(self, a: str, b: str) -> str:
        # a_index：指向字串 a 的最後一個索引（最低位元）
        # 因為二進位加法是「從右往左」進行
        a_index = len(a) - 1

        # b_index：指向字串 b 的最後一個索引（最低位元）
        b_index = len(b) - 1

        # carrier（進位）：
        # 用來記錄前一位相加後是否產生進位
        # 在二進位中，進位只可能是 0 或 1
        carrier = 0

        # answer 用來存放「每一位計算出來的結果」
        # 注意：這裡是從低位元開始 append，所以順序是反的
        answer = []

        # while 迴圈條件說明：
        # 只要符合以下三者之一，就必須繼續計算：
        # 1. a 還有未處理的位元
        # 2. b 還有未處理的位元
        # 3. 還有進位尚未處理（carrier == 1）
        while a_index >= 0 or b_index >= 0 or carrier:

            # ----------- 取出 a 的當前位元 -----------
            if a_index >= 0:
                # 將字元 '0' 或 '1' 轉成整數 0 或 1
                num_a = int(a[a_index])
                # 索引左移，準備處理下一個更高位元
                a_index -= 1
            else:
                # 如果 a 已經沒有位元可取
                # 則視為該位元是 0（補 0 的概念）
                num_a = 0

            # ----------- 取出 b 的當前位元 -----------
            if b_index >= 0:
                num_b = int(b[b_index])
                b_index -= 1
            else:
                # b 沒有位元時，同樣補 0
                num_b = 0

            # ----------- 本位元相加（含進位）-----------
            # total 可能的值只有 0, 1, 2, 3
            total = num_a + num_b + carrier

            # 新的進位：
            # 二進位中，只要 total >= 2 就會產生進位
            # total // 2 只可能是 0 或 1
            carrier = total // 2

            # 本位元的結果：
            # total % 2 取得「除以 2 的餘數」
            # 也就是該位元應該是 0 還是 1
            answer.append(str(total % 2))

            # 印出目前為止的結果（反轉後）
            # 這行是 debug 用，不影響演算法正確性
            # 可以清楚看到每一輪加法後的狀態
            print(answer[::-1])

        # answer 目前是「反向」的結果（從最低位到最高位）
        # 必須反轉回正確順序，並組合成字串回傳
        return "".join(answer[::-1])


