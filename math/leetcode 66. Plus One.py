from typing import List
# 從 typing 匯入 List
# 這是「型別提示（Type Hint）」
# 用來告訴閱讀者與工具：digits 會是一個整數的 List
# 不影響實際執行，只是輔助理解與檢查

class Solution:
    def plusOne(self, digits: List[int]) -> List[int]:
        # digits：代表一個「非負整數」
        # 每個元素都是一個位數（0~9）
        # 例如：
        # [1,2,3] 代表數字 123
        # [9,9,9] 代表數字 999

        # n 為 digits 的長度
        # 也就是這個整數的「位數」
        n = len(digits)

        # 從「最後一個位數（最低位）」開始往前處理
        # range(n-1, -1, -1) 的意思是：
        # n-1 → n-2 → ... → 1 → 0
        # 完全符合人類做加法「從個位數開始」的習慣
        for i in range(n - 1, -1, -1):

            # 如果目前位數不是 9
            # 代表加 1 不會產生進位
            if digits[i] != 9:
                # 直接將該位數加 1
                digits[i] += 1

                # 因為沒有進位，整個加法已經完成
                # 可以立刻回傳結果
                return digits

            # 若 digits[i] == 9
            # 則加 1 會變成 10
            # 本位數要變成 0，並且產生進位
            digits[i] = 0

            # 注意：這裡沒有 return
            # 會繼續往「更高位」處理進位

        # 如果 for 迴圈全部跑完都沒有 return
        # 代表「所有位數原本都是 9」
        # 例如：
        # [9,9,9] → [0,0,0]，最後還多一個進位

        # 此時正確結果應該是：
        # [1,0,0,0]
        # 也就是：
        # 在最前面補一個 1，後面補 n 個 0
        return [1] + [0] * n


# ------------------ 測試區 ------------------

digits = [5, 4, 3, 2, 1]
# 代表數字 54321

solution = Solution()

# 呼叫 plusOne，模擬對整數 +1
# 預期結果為 [5,4,3,2,2]
print(solution.plusOne(digits))


