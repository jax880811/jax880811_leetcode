class Solution:
    def isUgly(self, n: int) -> bool:
        """
        ============================================================
        【 核心演算法：質因數分解 (Prime Factorization) 的排除法 】
        ============================================================
        定義：醜數是指其「質因數」僅包含 2, 3, 5 的正整數。
        時間複雜度：O(log n)，因為每次整除都會讓 n 迅速變小。
        空間複雜度：O(1)，只使用了常數空間。
        """

        # 1. 邊界條件處理：
        # 根據題目定義，醜數必須是「正整數」。
        # 若 n <= 0，絕對不可能是醜數。
        if n <= 0:
            return False
        
        # --- [ ADT: List 的遍歷與語法糖 ] ---
        # 定義：List 是一組有序的元素集合。
        # 語法糖：for p in [2, 3, 5]
        # 說明：直接在程式碼中建立一個臨時清單並進行「迭代 (Iteration)」，
        #      不需要寫三個重複的 while 迴圈，保持代碼乾淨 (DRY 原則: Don't Repeat Yourself)。
        for p in [2, 3, 5]:
            
            # --- [ ADT: Integer 整數運算 ] ---
            # 1. 取餘數算符 (%): 
            #    n % p == 0 用來判斷 n 是否能被 p 整除（即 p 是否為 n 的因數）。
            
            # 2. 複合賦值與整除 (//=):
            #    語法糖：n //= p 
            #    說明：這等同於 n = n // p。
            #    注意：Python 的 // 是「整除 (Floor Division)」，保證結果依然是整數。
            #    對比：單斜線 / 在 Python 3 會強制轉為浮點數 (float)，在此不適用。
            
            while n % p == 0:
                n //= p  # 不斷地除以該質因數，直到「擠」不出來為止
        
        

        # 2. 最終判斷：
        # 如果 n 的質因數只有 2, 3, 5，那麼經過上面的擠壓，
        # 最後的 n 應該要剛好等於 1。
        # 如果最後 n > 1，代表它含有其他的質因數（例如 7, 11...），所以不是醜數。
        return n == 1

# ============================================================
# 【 超詳細深度筆記：數學與 ADT 知識點 】
# ============================================================
# 1. 數學邏輯：
#    任何正整數 $n$ 都可以寫成 $2^a \times 3^b \times 5^c \times (\text{其他質因數的乘積})$。
#    這題的目標就是把 $2^a, 3^b, 5^c$ 全部除掉。
#    如果「其他質因數的乘積」部分是 1，則 $n$ 就是醜數。
#
# 2. Python 語法糖總結：
#    - [a, b, c]：快速建立 List 物件。
#    - for x in list：直接走訪元素 (Iterator 模式)，比用 index 存取更優雅。
#    - a //= b：原地 (In-place) 修改變數值的快捷寫法。
#
# 3. 為什麼不需要檢查質數？
#    你會發現我們只除以 2, 3, 5。我們不需要擔心 4 (因為它已經被 2 除光了)
#    或 6 (因為它會被 2 和 3 除光)。這是「貪婪除法」的一種應用。
# ============================================================


n = int(input())

solution = Solution()


print(solution.isUgly(n))